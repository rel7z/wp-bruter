#!/usr/bin/env python3
"""Local mock WordPress targets for validating wp-bruter behavior.

Ports:
  9190 clean WP (admin/letmein)   -> should crack, verified_success
  9191 always 429                 -> skipped rate_limited at quickCheck
  9192 Wordfence signature        -> skipped waf_wordfence at quickCheck
  9193 9s slow login page         -> skipped slow at quickCheck
  9194 GET ok / POST 429          -> job starts, then stops rate_limited
"""
import json
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, parse_qs

LOGIN_FORM = (b'<html><body><form name="loginform" action="wp-login.php" method="post">'
              b'<input type="text" name="log"/><input type="password" name="pwd"/>'
              b'<input type="submit" name="wp-submit"/></form></body></html>')


def make_handler(mode, port):
    class H(BaseHTTPRequestHandler):
        def log_message(self, *args):
            pass

        def _send(self, code, body=b"", headers=None, write_body=True):
            self.send_response(code)
            for k, v in (headers or {}).items():
                self.send_header(k, v)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            if body and write_body:
                self.wfile.write(body)

        def do_HEAD(self):
            path = urlparse(self.path).path
            if path == "/" and "author=" in self.path:
                self._send(301, b"", {"Location": "/author/admin"}, write_body=False)
            else:
                self._send(200, LOGIN_FORM, write_body=False)

        def do_GET(self):
            path = urlparse(self.path).path
            if mode == "slow":
                time.sleep(9)
            if mode == "ratelimit":
                return self._send(429, b"too many requests")
            if path.startswith("/wp-json/wp/v2/users") or "rest_route=/wp/v2/users" in self.path:
                return self._send(200, json.dumps([{"id": 1, "slug": "admin"}]).encode(),
                                  {"Content-Type": "application/json"})
            if path == "/wp-login.php":
                if mode == "wordfence":
                    return self._send(200, LOGIN_FORM + b"<!-- Generated by Wordfence -->")
                return self._send(200, LOGIN_FORM)
            return self._send(200, b"mock wordpress")

        def do_POST(self):
            length = int(self.headers.get("Content-Length", 0))
            body = self.rfile.read(length).decode()
            params = {k: v[0] for k, v in parse_qs(body).items()}
            if mode in ("ratelimit", "blockonpost"):
                return self._send(429, b"rate limited")
            if mode == "slow":
                time.sleep(9)
            if self.path.startswith("/wp-login.php"):
                if params.get("log") == "admin" and params.get("pwd") == "letmein":
                    return self._send(302, b"", {"Location": f"http://127.0.0.1:{port}/wp-admin/"})
                return self._send(200, LOGIN_FORM + b"<div>Error: incorrect password</div>")
            return self._send(404, b"")

    return H


modes = {
    9190: "clean",
    9191: "ratelimit",
    9192: "wordfence",
    9193: "slow",
    9194: "blockonpost",
}

for port, mode in modes.items():
    srv = ThreadingHTTPServer(("127.0.0.1", port), make_handler(mode, port))
    threading.Thread(target=srv.serve_forever, daemon=True).start()

print("mock targets on 127.0.0.1:9190-9194", flush=True)
threading.Event().wait()
